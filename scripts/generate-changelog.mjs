#!/usr/bin/env node
/**
 * Regenerates src/lib/changelog.generated.ts from git history — the "Recent Updates" tab's
 * SHIPPED_UPDATES list used to be hand-maintained (see the old comment in changelog.ts) and
 * routinely went stale because shipping a change and writing a changelog entry were two
 * separate, easy-to-forget steps. This folds them into one: every PR merged to main already
 * has a human-written, customer-presentable title (that's the convention this repo's commit
 * messages follow), so the changelog is just that history, reformatted.
 *
 * Runs as `prebuild`/`predev` (see package.json) so it's always current without anyone having
 * to remember to run it. Safe to run anywhere `git log` works; if the checkout is too shallow
 * (a handful of commits or fewer — can happen on a shallow CI clone) it leaves the previously
 * generated file alone rather than overwriting a good list with a sparse one.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = join(__dirname, "..", "src", "lib", "changelog.generated.ts");
const MIN_COMMITS = 5;
const MAX_ENTRIES = 120;
const MAX_DESCRIPTION_LENGTH = 280;

const RECORD_SEP = "\x1e";
const FIELD_SEP = "\x1f";
const TRAILER_LINE = /^(co-authored-by|claude-session|signed-off-by|reviewed-by):/i;
const PR_SUFFIX = /\s*\(#\d+\)\s*$/;

function gitLog() {
  try {
    return execFileSync("git", ["log", `--pretty=format:%ad${FIELD_SEP}%s${FIELD_SEP}%b${RECORD_SEP}`, "--date=short", `-n`, "500"], {
      cwd: join(__dirname, ".."),
      encoding: "utf8",
    });
  } catch {
    return null;
  }
}

function bodyToDescription(body) {
  const lines = body
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !TRAILER_LINE.test(l))
    .map((l) => l.replace(/^[-*]\s+/, ""));
  let text = lines.join(" ").replace(/\s+/g, " ").trim();
  if (text.length > MAX_DESCRIPTION_LENGTH) text = text.slice(0, MAX_DESCRIPTION_LENGTH - 1).trimEnd() + "…";
  return text;
}

function parseEntries(raw) {
  return raw
    .split(RECORD_SEP)
    .map((r) => r.trim())
    .filter(Boolean)
    .map((record) => {
      const [date, subject, body = ""] = record.split(FIELD_SEP);
      return { date, subject, body };
    })
    .filter((r) => PR_SUFFIX.test(r.subject))
    .map((r) => ({
      date: r.date,
      title: r.subject.replace(PR_SUFFIX, "").trim(),
      description: bodyToDescription(r.body),
    }))
    .slice(0, MAX_ENTRIES);
}

function serialize(entries) {
  const header = `/**
 * AUTO-GENERATED by scripts/generate-changelog.mjs — do not hand-edit.
 * Regenerated on every \`npm run build\`/\`npm run dev\` (see package.json's prebuild/predev
 * hooks) from the merged-PR titles and bodies in git history. To change what shows up here,
 * change the PR title/description you merge, not this file.
 */

import type { ChangelogEntry } from "./changelog";

export const SHIPPED_UPDATES: ChangelogEntry[] = `;
  return header + JSON.stringify(entries, null, 2) + ";\n";
}

function main() {
  const raw = gitLog();
  if (!raw) {
    console.warn("[generate-changelog] `git log` unavailable — leaving changelog.generated.ts as-is.");
    return;
  }
  const entries = parseEntries(raw);
  if (entries.length < MIN_COMMITS) {
    console.warn(`[generate-changelog] only found ${entries.length} entries (shallow clone?) — leaving changelog.generated.ts as-is.`);
    return;
  }
  const next = serialize(entries);
  if (existsSync(OUT_PATH) && readFileSync(OUT_PATH, "utf8") === next) return;
  writeFileSync(OUT_PATH, next);
  console.log(`[generate-changelog] wrote ${entries.length} entries to ${OUT_PATH}`);
}

main();
